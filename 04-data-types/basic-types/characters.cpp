#include <iostream>
using namespace std;

int main() {
    char myGrade = 'A';

    cout << "char: " << myGrade << endl;

    char a = 65, b = 66, c = 67;
    cout << "Characters: " << a << ", " << b << ", " << c << endl;

    char name[] = "Ahmed";
    cout << "Name: " << name << endl;

    return 0;
}

// Output:

// char: A
// Characters: A, B, C
// Name: Ahmed